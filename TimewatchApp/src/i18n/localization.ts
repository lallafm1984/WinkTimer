const translations: Record<AppLocale, TranslationMap> = {
  'en-US': englishTranslations,
  ...translationOverrides,
};

export function getMissingTranslationKeys(locale: AppLocale) {
  const localeTranslations = translations[locale];

  return translationKeys.filter(key => {
    const value = localeTranslations[key];

    return typeof value !== 'string' || value.trim().length === 0;
  });
}

function formatTranslation(template: string, params?: TranslationParams) {
  if (params === undefined) {
    return template;
  }

  return Object.entries(params).reduce(
    (current, [key, value]) =>
      current.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value)),
    template,
  );
}

function normalizeLanguageTag(value: unknown) {
  if (typeof value !== 'string') {
    return null;
  }

  const trimmed = value.trim();
  if (trimmed.length === 0) {
    return null;
  }

  const parts = trimmed.replace(/_/g, '-').split('-').filter(Boolean);
  const language = parts[0]?.toLowerCase();
  if (!language) {
    return null;
  }

  const region = parts.find((part, index) => index > 0 && part.length === 2);
  return region === undefined
    ? language
    : `${language}-${region.toUpperCase()}`;
}

function resolveSupportedLocale(value: unknown): AppLocale {
  const normalized = normalizeLanguageTag(value);
  if (normalized === null) {
    return DEFAULT_APP_LOCALE;
  }

  if (supportedLocaleSet.has(normalized as AppLocale)) {
    return normalized as AppLocale;
  }

  const language = normalized.split('-')[0];

  return languageToLocale[language] ?? DEFAULT_APP_LOCALE;
}

export function normalizeAppLocale(value: unknown): AppLocale {
  return resolveSupportedLocale(value);
}

export function getDeviceAppLocale(): AppLocale {
  const nativeModules = NativeModules as LocaleNativeModules;
  const settings = nativeModules.SettingsManager?.settings;
  const appleLocale = settings?.AppleLocale;
  const appleLanguage = settings?.AppleLanguages?.[0];
  const nativeLocale = nativeModules.I18nManager?.localeIdentifier;
  const intlLocale =
    typeof Intl !== 'undefined'
      ? Intl.DateTimeFormat().resolvedOptions().locale
      : undefined;

  return resolveSupportedLocale(
    appleLanguage ?? appleLocale ?? nativeLocale ?? intlLocale,
  );
}

export function createTranslator(locale: AppLocale) {
  return (key: TranslationKey, params?: TranslationParams) => {
    const template = translations[locale][key] ?? englishTranslations[key] ?? key;

    return formatTranslation(template, params);
  };
}

