export function getLocalizedModeHint(
  locale: AppLocale,
  mode: TimerModePreset,
  label: string,
) {
  const action = mode.actions.find(item => item.label === label);
  if (action === undefined) {
    return '-';
  }

  const t = createTranslator(locale);
  const key = gestureLabelKeys[action.value];

  return key === undefined ? action.value : t(key);
}

export function getLocalizedModeActionSummary(
  locale: AppLocale,
  mode: TimerModePreset,
) {
  const t = createTranslator(locale);
  const actionGroups: Array<{labels: string[]; value: string}> = [];

  mode.actions.forEach(action => {
    const labelKey = actionLabelKeys[action.label];
    const gestureKey = gestureLabelKeys[action.value];
    const label = labelKey === undefined ? action.label : t(labelKey);
    const value = gestureKey === undefined ? action.value : t(gestureKey);
    const previousGroup = actionGroups[actionGroups.length - 1];

    if (previousGroup?.value === value) {
      previousGroup.labels.push(label);
      return;
    }

    actionGroups.push({labels: [label], value});
  });

  return actionGroups
    .map(group => `${group.labels.join('/')}: ${group.value}`)
    .join(' · ');
}

